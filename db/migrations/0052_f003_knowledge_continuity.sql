-- Work context and derived answers share the existing immutable application
-- record ledger. No competing Claim/Decision/Execution truth is introduced.
ALTER TABLE understanding_record DROP CONSTRAINT understanding_record_record_type_check;
ALTER TABLE understanding_record ADD CONSTRAINT understanding_record_record_type_check CHECK (record_type IN (
  'ARTIFACT_INVENTORY','EXTRACTOR_CAPABILITY','UNDERSTANDING_PLAN','WORK_UNIT',
  'MODEL_CAPABILITY_PROFILE','ANALYSIS_ROUTE_DECISION','SOURCE_SLICE',
  'RECONCILIATION','EVALUATION_RUN','GRAPH_ARTIFACT','GRAPH_REVISION',
  'SOURCE_REGISTRATION','FACT_BUNDLE','CANDIDATE_BUNDLE','EVIDENCE_ALLOWSET',
  'GAP','WORKSPACE_ANALYSIS_JOB','WORKSPACE_STATE','WORKSPACE_EVENT',
  'WORKSPACE_VIEW_PREFERENCE','WORKSPACE_CAPABILITY_CONFIG','WORKSPACE_EXECUTION_PROFILE',
  'PROJECT_CAPABILITY_REVISION','WORKSPACE_CAPABILITY_DRAFT','WORKSPACE_POLICY_REVISION',
  'SECRET_GRANT','ANALYSIS_BATCH','CHILD_WORK_UNIT','CHILD_BATCH_RESULT',
  'BATCH_BARRIER','CONFLICT_LEDGER','COVERAGE_LEDGER','QUARANTINED_CANDIDATE',
  'REVIEW_QUEUE_ITEM','REVIEW_BATCH_DECISION','FEATURE_HISTORY',
  'SOURCE_SLICE_AUTH_AUDIT','INCREMENTAL_PLAN','EQUIVALENCE_REPORT',
  'UNDERSTANDING_SEMANTIC_SURFACE','INDEPENDENT_ANALYSIS_RUN','REVIEWED_MEASUREMENT','MAIN_BATCH_RESULT',
  'WORK_SESSION','WORK_SESSION_EVENT','KNOWLEDGE_QUESTION','KNOWLEDGE_ANSWER','KNOWLEDGE_FEEDBACK'
));
CREATE TRIGGER f003_immutable_work_record BEFORE UPDATE OR DELETE ON understanding_record
  FOR EACH ROW WHEN (OLD.record_type IN ('WORK_SESSION','WORK_SESSION_EVENT','KNOWLEDGE_QUESTION','KNOWLEDGE_ANSWER','KNOWLEDGE_FEEDBACK'))
  EXECUTE FUNCTION reject_immutable_mutation();
CREATE UNIQUE INDEX f003_work_record_operation ON understanding_record
  (project_id,record_type,(record_payload->>'actorId'),(record_payload->>'operationId'))
  WHERE record_type IN ('WORK_SESSION','KNOWLEDGE_QUESTION','KNOWLEDGE_FEEDBACK');
CREATE UNIQUE INDEX f003_work_session_event_version ON understanding_record
  (project_id,(record_payload->>'sessionId'),((record_payload->>'version')::integer))
  WHERE record_type='WORK_SESSION_EVENT';
CREATE INDEX f003_work_session_record_page ON understanding_record
  (project_id,(record_payload->>'sessionId'),created_at,id)
  WHERE record_type IN ('KNOWLEDGE_QUESTION','KNOWLEDGE_FEEDBACK');
